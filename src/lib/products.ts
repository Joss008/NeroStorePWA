export function getProducts(category?: Category): Product[] {
  if (!category) return products;
  return products.filter((p) => p.category === category);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getFeatured(): Product[] {
  const popular = products.filter((p) => p.popular);
  const discounted = products.filter((p) => p.originalPrices && Object.values(p.originalPrices).some((v) => v && v > 0));
  const combined = [...popular, ...discounted];
  const unique = Array.from(new Map(combined.map((p) => [p.id, p])).values());
  return unique.slice(0, 8);
}

export function getRelated(productId: string, limit = 4): Product[] {
  const product = products.find((p) => p.id === productId);
  if (!product) return [];
  return products
    .filter((p) => p.id !== productId && p.category === product.category)
    .slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.shortDescription.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q)
  );
}
